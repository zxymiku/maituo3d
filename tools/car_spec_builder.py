def rect_part(
    pid: str,
    name: str,
    sub: str,
    cat: str,
    proc: str,
    mat: str,
    color: str,
    qty: int,
    size: Tuple[float, float, float],
    note: str,
    dims: List[Tuple[str, str, str]],
    plane: str = "XY",
    fillet: float = 2.0,
    holes: List[Dict[str, object]] | None = None,
) -> Dict[str, object]:
    sx, sy, sz = size
    if plane == "XY":
        w, h, d = sx, sy, sz
    elif plane == "XZ":
        w, h, d = sx, sz, sy
    else:
        w, h, d = sy, sz, sx
    return {
        "id": pid,
        "name": name,
        "subsystem": sub,
        "category": cat,
        "process": proc,
        "material": mat,
        "color": color,
        "quantity": qty,
        "size": [float(sx), float(sy), float(sz)],
        "note": note,
        "keyDimensions": [{"name": k, "value": v, "note": n} for k, v, n in dims],
        "features": [
            {
                "id": f"{pid}-F01",
                "name": f"{name}主体拉伸",
                "type": "拉伸凸台",
                "plane": plane,
                "w0": -0.5 * d,
                "w1": 0.5 * d,
                "shape": "rect",
                "params": {"cx": 0.0, "cy": 0.0, "w": float(w), "h": float(h), "fillet": float(fillet)},
                "holes": holes or [],
            }
        ],
    }


def cyl_part(
    pid: str,
    name: str,
    sub: str,
    cat: str,
    proc: str,
    mat: str,
    color: str,
    qty: int,
    outer_d: float,
    length: float,
    note: str,
    dims: List[Tuple[str, str, str]],
    plane: str = "XY",
    bore_d: float = 0.0,
) -> Dict[str, object]:
    r = 0.5 * outer_d
    if plane == "XY":
        size = [outer_d, outer_d, length]
    elif plane == "XZ":
        size = [outer_d, length, outer_d]
    else:
        size = [length, outer_d, outer_d]
    holes = [{"shape": "circle", "cx": 0.0, "cy": 0.0, "r": 0.5 * bore_d}] if bore_d > 0 else []
    return {
        "id": pid,
        "name": name,
        "subsystem": sub,
        "category": cat,
        "process": proc,
        "material": mat,
        "color": color,
        "quantity": qty,
        "size": [round(x, 2) for x in size],
        "note": note,
        "keyDimensions": [{"name": k, "value": v, "note": n} for k, v, n in dims],
        "features": [
            {
                "id": f"{pid}-F01",
                "name": f"{name}回转体拉伸",
                "type": "拉伸凸台",
                "plane": plane,
                "w0": -0.5 * length,
                "w1": 0.5 * length,
                "shape": "circle",
                "params": {"cx": 0.0, "cy": 0.0, "r": float(r)},
                "holes": holes,
            }
        ],
    }


def gear_part(
    pid: str,
    name: str,
    sub: str,
    cat: str,
    proc: str,
    mat: str,
    color: str,
    qty: int,
    module_mm: float,
    teeth: int,
    thickness: float,
    bore_d: float,
    note: str,
    dims: List[Tuple[str, str, str]],
    plane: str = "XZ",
) -> Dict[str, object]:
    da = module_mm * (teeth + 2)
    if plane == "XY":
        size = [da, da, thickness]
    elif plane == "XZ":
        size = [da, thickness, da]
    else:
        size = [thickness, da, da]
    holes = [{"shape": "circle", "cx": 0.0, "cy": 0.0, "r": 0.5 * bore_d}]
    if da >= 28.0:
        for cx, cy in ((9.0, 0.0), (-9.0, 0.0), (0.0, 9.0), (0.0, -9.0)):
            holes.append({"shape": "circle", "cx": cx, "cy": cy, "r": 3.0})
    return {
        "id": pid,
        "name": name,
        "subsystem": sub,
        "category": cat,
        "process": proc,
        "material": mat,
        "color": color,
        "quantity": qty,
        "size": [round(x, 2) for x in size],
        "note": note,
        "keyDimensions": [{"name": k, "value": v, "note": n} for k, v, n in dims],
        "features": [
            {
                "id": f"{pid}-F01",
                "name": f"{name}渐开线齿廓拉伸",
                "type": "齿轮轮廓拉伸",
                "plane": plane,
                "w0": -0.5 * thickness,
                "w1": 0.5 * thickness,
                "shape": "gear",
                "params": {"module": float(module_mm), "teeth": int(teeth)},
                "holes": holes,
            }
        ],
    }


